#!/usr/bin/env python3
"""Writes Packages/DelulutopiaKit/Sources/Core/I18n/Catalog.swift from the web's catalogues
(tools/i18n/web/*.json, copied from delululand-web src/i18n/messages) and the app's own sentences
(tools/i18n/mobile.json). Keys are the web's, so every platform says the same thing.

    python3 tools/i18n/generate.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.join(ROOT, 'tools', 'i18n')
OUT = os.path.join(ROOT, 'Packages', 'DelulutopiaKit', 'Sources', 'Core', 'I18n', 'Catalog.swift')
LANGS = ('en', 'az', 'fa', 'tr', 'ru')


def load():
    cat = {lang: json.load(open(os.path.join(HERE, 'web', f'{lang}.json'), encoding='utf-8')) for lang in LANGS}
    mobile = json.load(open(os.path.join(HERE, 'mobile.json'), encoding='utf-8'))
    for key, texts in mobile.items():
        if key in cat['en'] and cat['en'][key] != texts['en']:
            sys.exit(f'{key}: mobile.json changes the web English; use a new key')
        for lang in LANGS:
            cat[lang][key] = texts[lang]
    ph = lambda s: set(re.findall(r'\{([A-Za-z]+)\}', s))
    for key, en in cat['en'].items():
        for lang in LANGS[1:]:
            if key not in cat[lang]:
                sys.exit(f'{lang} misses {key}')
            if not ph(cat[lang][key]) <= ph(en):
                sys.exit(f'{lang} {key}: placeholders {ph(cat[lang][key]) - ph(en)} are not in English')
    return cat


def sw(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    cat = load()
    lines = [
        '// Generated by tools/i18n/generate.py from the web catalogues and tools/i18n/mobile.json. Do not edit.',
        '// swiftlint:disable all',
        '',
        'enum Catalog {',
        '    static func of(_ lang: Lang) -> [String: String] {',
        '        switch lang {',
        '        case .en: en',
        '        case .az: az',
        '        case .fa: fa',
        '        case .tr: tr',
        '        case .ru: ru',
        '        }',
        '    }',
    ]
    for lang in LANGS:
        lines.append('')
        lines.append(f'    static let {lang}: [String: String] = [')
        for k in sorted(cat[lang]):
            lines.append(f'        {sw(k)}: {sw(cat[lang][k])},')
        lines.append('    ]')
    lines.append('}')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(cat["en"])} keys')


if __name__ == '__main__':
    main()
